"""Run the direct 2-SAT challenge on exposed WAP05/06 development graphs.

The graph topologies are pinned public upstream bytes. Lists and restrictions are
the already disclosed synthetic workload generated by the historical MiniCard
filter. This script cannot turn WAP05/06 into a new holdout.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from .cases import export_wap, load_case
from .direct_twosat_benchmark import run as run_challenge

UPSTREAM_REPOSITORY = "marijnheule/clicolcom"
UPSTREAM_COMMIT = "4932048642da2144f387961b595112277afff82f"
GRAPH_INVENTORY = {
    "wap05a.col": {
        "bytes": 426775,
        "git_blob_sha1": "327cc0c6b1abbc4a9ee31c14f3357136e5b186ec",
    },
    "wap06a.col": {
        "bytes": 431449,
        "git_blob_sha1": "60ca46d3198c02176be8812d8f53357e3b9f4114",
    },
}
COUNTS = (1, 8, 64, 1024)
CLASSIFICATION = (
    "exposed WAP05/06 development diagnostic; real public conflict topologies, "
    "synthetic lists and historically SAT-filtered restrictions; no holdout, "
    "operator-trace or SOTA claim"
)


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _git_blob_sha1(data: bytes) -> str:
    header = f"blob {len(data)}\0".encode("ascii")
    return hashlib.sha1(header + data).hexdigest()


def _verify_graphs(graph_dir: Path) -> dict:
    receipt = {
        "schema": "spectra.direct_twosat_wap_graphs.v1",
        "repository": UPSTREAM_REPOSITORY,
        "commit": UPSTREAM_COMMIT,
        "classification": CLASSIFICATION,
        "graphs": {},
    }
    for name, expected in GRAPH_INVENTORY.items():
        path = graph_dir / name
        data = path.read_bytes()
        blob = _git_blob_sha1(data)
        if len(data) != expected["bytes"]:
            raise ValueError(f"{name}: byte length differs from the pinned inventory")
        if blob != expected["git_blob_sha1"]:
            raise ValueError(f"{name}: Git-blob identity differs from the pinned inventory")
        receipt["graphs"][name] = {
            "bytes": len(data),
            "git_blob_sha1": blob,
            "sha256": _sha256(data),
        }
    return receipt


def run(
    graph_dir: Path,
    spectra_library: Path,
    direct_library: Path,
    destination: Path,
    *,
    repeats: int = 24,
) -> dict:
    graph_dir = graph_dir.resolve(strict=True)
    destination = destination.resolve()
    destination.mkdir(parents=True, exist_ok=False)

    graph_receipt = _verify_graphs(graph_dir)
    graph_receipt_path = destination / "graph-inventory.json"
    graph_receipt_path.write_text(
        json.dumps(graph_receipt, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    cases_dir = destination / "cases"
    export_wap(graph_dir, cases_dir)
    cases = []
    case_receipts = {}
    for name in GRAPH_INVENTORY:
        case_path = cases_dir / f"{name}.json"
        case, case_sha256 = load_case(case_path)
        if len(case.queries) != max(COUNTS):
            raise AssertionError(f"{name}: generated query count differs")
        cases.append(case)
        case_receipts[name] = {
            "case": case_path.relative_to(destination).as_posix(),
            "case_sha256": case_sha256,
            "cluster": case.cluster,
            "provenance": case.provenance,
            "vertices": case.problem.n,
            "edges": len(case.problem.edges),
            "palette": case.problem.palette,
            "queries": len(case.queries),
            "generation_receipt": (
                cases_dir / f"{name}.generation.json"
            ).relative_to(destination).as_posix(),
        }
    (destination / "case-inventory.json").write_text(
        json.dumps(
            {
                "schema": "spectra.direct_twosat_wap_cases.v1",
                "classification": CLASSIFICATION,
                "cases": case_receipts,
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    result = run_challenge(
        spectra_library.resolve(strict=True),
        direct_library.resolve(strict=True),
        destination / "benchmark",
        repeats=repeats,
        cases=tuple(cases),
        counts=COUNTS,
        classification=CLASSIFICATION,
    )
    summary = {
        "schema": "spectra.direct_twosat_wap_summary.v1",
        "classification": CLASSIFICATION,
        "upstream": {
            "repository": UPSTREAM_REPOSITORY,
            "commit": UPSTREAM_COMMIT,
        },
        "graphs": graph_receipt["graphs"],
        "cases": case_receipts,
        "benchmark_schema": result["schema"],
        "platform": result["platform"],
        "machine": result["machine"],
        "repeats": result["repeats"],
        "counts": result["counts"],
        "summary": result["summary"],
    }
    (destination / "summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return summary


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--graph-dir", type=Path, required=True)
    parser.add_argument("--spectra-library", type=Path, required=True)
    parser.add_argument("--direct-library", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--repeats", type=int, default=24)
    args = parser.parse_args(argv)
    result = run(
        args.graph_dir,
        args.spectra_library,
        args.direct_library,
        args.out,
        repeats=args.repeats,
    )
    print(json.dumps(result["summary"], indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
