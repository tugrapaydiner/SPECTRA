"""Deterministic WAP list-colouring workload construction.

The source graph topology is public application data. Availability lists and
support queries are deliberately synthetic and are generated by this fixed code;
they are not claimed to be deployed optical-network traces. The generator uses a
pinned native MiniCard only to retain the first satisfiable random restrictions,
which is conservative for the primary MiniCard comparison.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
import hashlib
import heapq
import json
from pathlib import Path
import random
from typing import Iterable, Sequence

from experiments.critical_clique_coloring.core import Graph, parse_dimacs_col, verify_coloring

SCHEMA = "spectra.wap_support.case.v1"
MASTER_SEED = 0x9E3779B97F4A7C15
QUERY_COUNT = 1024
QUERY_WIDTH = 8
MAX_GENERATOR_ATTEMPTS = 20000
MIN_UNIQUE_ORACLE_MODELS = 768


def _sha_json(value: object) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def deterministic_dsatur(graph: Graph) -> tuple[int, ...]:
    """Deterministic DSATUR with saturation, degree, then vertex-id ordering."""
    colors = [-1] * graph.n
    saturation = [set() for _ in range(graph.n)]
    degree = [len(row) for row in graph.adjacency]
    version = [0] * graph.n
    heap = [(0, -degree[v], v, 0) for v in range(graph.n)]
    heapq.heapify(heap)
    for _ in range(graph.n):
        while True:
            negative_saturation, _negative_degree, vertex, observed = heapq.heappop(heap)
            if (colors[vertex] < 0 and observed == version[vertex]
                    and -negative_saturation == len(saturation[vertex])):
                break
        color = 0
        while color in saturation[vertex]:
            color += 1
        colors[vertex] = color
        for neighbor in graph.adjacency[vertex]:
            if colors[neighbor] < 0 and color not in saturation[neighbor]:
                saturation[neighbor].add(color)
                version[neighbor] += 1
                heapq.heappush(heap, (-len(saturation[neighbor]), -degree[neighbor],
                                      neighbor, version[neighbor]))
    result = tuple(colors)
    verify_coloring(graph, result, max(result, default=-1) + 1)
    return result


def rotating_triple_masks(coloring: Sequence[int]) -> tuple[int, tuple[int, ...]]:
    """Map each three color classes to {a,b}, {b,c}, {c,a} binary lists.

    This construction preserves the supplied proper coloring and creates
    implication cycles that full SCC substitution can identify but same-list
    parity contraction generally cannot. More than 63 DSATUR colors is an honest
    workload-admission failure under the native <=64-color contract.
    """
    if not coloring:
        return 0, ()
    if any(type(c) is not int or c < 0 for c in coloring):
        raise ValueError("coloring must contain nonnegative exact integers")
    color_count = max(coloring) + 1
    palette = ((color_count + 2) // 3) * 3
    if palette > 63:
        raise ValueError("DSATUR uses too many colors for rotating triples")
    masks = []
    for color in coloring:
        base, position = divmod(color, 3)
        first = 3 * base + position
        second = 3 * base + ((position + 1) % 3)
        masks.append((1 << first) | (1 << second))
    return palette, tuple(masks)


def binary_colors(mask: int) -> tuple[int, int]:
    if type(mask) is not int or mask <= 0 or mask.bit_count() != 2:
        raise ValueError("every workload domain must contain exactly two colors")
    low = (mask & -mask).bit_length() - 1
    high = (mask ^ (mask & -mask)).bit_length() - 1
    return low, high


def choice_literal(vertex: int, color: int, masks: Sequence[int]) -> int:
    low, high = binary_colors(masks[vertex])
    if color == low:
        return -(vertex + 1)
    if color == high:
        return vertex + 1
    raise ValueError("color is outside the vertex list")


def compact_binary_clauses(graph: Graph, masks: Sequence[int]) -> tuple[tuple[int, ...], ...]:
    """One Boolean per vertex; each shared edge color produces one binary clause."""
    if len(masks) != graph.n:
        raise ValueError("mask count differs from graph")
    clauses: list[tuple[int, ...]] = []
    for left, right in graph.edges:
        shared = masks[left] & masks[right]
        while shared:
            bit = shared & -shared
            shared ^= bit
            color = bit.bit_length() - 1
            clauses.append((-choice_literal(left, color, masks),
                            -choice_literal(right, color, masks)))
    return tuple(clauses)


def model_to_labels(model: Sequence[int], masks: Sequence[int]) -> bytes:
    positive = {literal for literal in model if literal > 0}
    output = bytearray(len(masks))
    for vertex, mask in enumerate(masks):
        low, high = binary_colors(mask)
        output[vertex] = high if vertex + 1 in positive else low
    return bytes(output)


def restrictions_to_assumptions(restrictions: Sequence[Sequence[int]],
                                masks: Sequence[int]) -> list[int]:
    assumptions = []
    for item in restrictions:
        if type(item) not in (tuple, list) or len(item) != 2:
            raise ValueError("restriction must be a vertex/mask pair")
        vertex, allowed = item
        if type(vertex) is not int or not 0 <= vertex < len(masks):
            raise ValueError("restriction vertex outside graph")
        if type(allowed) is not int or allowed <= 0 or allowed.bit_count() != 1:
            raise ValueError("generated restriction must be a singleton mask")
        assumptions.append(choice_literal(vertex, allowed.bit_length() - 1, masks))
    return assumptions


def verify_labels(graph: Graph, palette: int, masks: Sequence[int],
                  restrictions: Sequence[Sequence[int]], labels: bytes) -> bool:
    if type(labels) is not bytes or len(labels) != graph.n:
        return False
    for vertex, color in enumerate(labels):
        if color >= palette or not ((masks[vertex] >> color) & 1):
            return False
    if any(labels[left] == labels[right] for left, right in graph.edges):
        return False
    for vertex, allowed in restrictions:
        if not ((allowed >> labels[vertex]) & 1):
            return False
    return True


@dataclass(frozen=True)
class WorkloadCase:
    schema: str
    graph_name: str
    graph_sha256: str
    graph_git_blob_sha1: str
    n: int
    edges: tuple[tuple[int, int], ...]
    dsatur_coloring: tuple[int, ...]
    dsatur_colors: int
    palette: int
    masks: tuple[int, ...]
    queries: tuple[tuple[tuple[int, int], ...], ...]
    generator_attempts: int
    generator_rejections: int
    generator_unique_model_hashes: int
    generator_seed: int
    query_width: int
    query_count: int
    clauses: int
    case_sha256: str

    def canonical_without_hash(self) -> dict:
        data = asdict(self)
        data.pop("case_sha256")
        return data

    def validate(self) -> None:
        if self.schema != SCHEMA or self.n != len(self.masks) or self.n != len(self.dsatur_coloring):
            raise ValueError("invalid case geometry")
        if self.query_count != len(self.queries) or self.query_width != QUERY_WIDTH:
            raise ValueError("invalid query inventory")
        if len(set(self.queries)) != len(self.queries):
            raise ValueError("duplicate generated query")
        if self.case_sha256 != _sha_json(self.canonical_without_hash()):
            raise ValueError("case digest mismatch")

    def to_json(self, path: str | Path) -> None:
        Path(path).write_text(json.dumps(asdict(self), sort_keys=True,
                                         separators=(",", ":")) + "\n")

    @classmethod
    def from_json(cls, path: str | Path) -> "WorkloadCase":
        raw = json.loads(Path(path).read_text())
        raw["edges"] = tuple(tuple(x) for x in raw["edges"])
        raw["dsatur_coloring"] = tuple(raw["dsatur_coloring"])
        raw["masks"] = tuple(raw["masks"])
        raw["queries"] = tuple(tuple(tuple(item) for item in q) for q in raw["queries"])
        case = cls(**raw)
        case.validate()
        return case


def _git_blob_sha1(data: bytes) -> str:
    return hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest()


def build_case(graph_path: str | Path, *, graph_name: str | None = None,
               expected_git_blob_sha1: str | None = None,
               query_count: int = QUERY_COUNT, query_width: int = QUERY_WIDTH,
               master_seed: int = MASTER_SEED) -> tuple[WorkloadCase, dict]:
    """Construct a fixed case; MiniCard filters only satisfiable random queries."""
    from pysat.solvers import Solver  # optional research dependency

    source = Path(graph_path)
    graph_bytes = source.read_bytes()
    blob = _git_blob_sha1(graph_bytes)
    if expected_git_blob_sha1 is not None and blob != expected_git_blob_sha1:
        raise ValueError("graph Git-blob identity mismatch")
    graph = parse_dimacs_col(source, name=graph_name or source.name)
    coloring = deterministic_dsatur(graph)
    palette, masks = rotating_triple_masks(coloring)
    clauses = compact_binary_clauses(graph, masks)
    seed = (master_seed ^ int(graph.sha256[:16], 16) ^ (graph.n << 17) ^ graph.m) & ((1 << 64) - 1)
    rng = random.Random(seed)
    solver = Solver(name="minicard", bootstrap_with=clauses)
    queries: list[tuple[tuple[int, int], ...]] = []
    accepted_models: set[str] = set()
    attempts: list[dict] = []
    seen: set[tuple[tuple[int, int], ...]] = set()
    rejected = 0
    try:
        while len(queries) < query_count:
            if len(attempts) >= MAX_GENERATOR_ATTEMPTS:
                raise RuntimeError("query generator exhausted its frozen attempt budget")
            vertices = sorted(rng.sample(range(graph.n), query_width))
            query = []
            for vertex in vertices:
                choices = binary_colors(masks[vertex])
                color = choices[rng.randrange(2)]
                query.append((vertex, 1 << color))
            candidate = tuple(query)
            if candidate in seen:
                attempts.append({"query_sha256": _sha_json(candidate), "duplicate": True})
                continue
            seen.add(candidate)
            assumptions = restrictions_to_assumptions(candidate, masks)
            sat = solver.solve(assumptions=assumptions)
            record = {"query_sha256": _sha_json(candidate), "duplicate": False, "sat": bool(sat)}
            if not sat:
                rejected += 1
                attempts.append(record)
                continue
            model = solver.get_model()
            if model is None:
                raise AssertionError("MiniCard returned SAT without a model")
            labels = model_to_labels(model, masks)
            if not verify_labels(graph, palette, masks, candidate, labels):
                raise AssertionError("query-generation oracle returned an invalid witness")
            model_hash = hashlib.sha256(labels).hexdigest()
            record["model_sha256"] = model_hash
            attempts.append(record)
            accepted_models.add(model_hash)
            queries.append(candidate)
    finally:
        solver.delete()
    if len(accepted_models) < min(MIN_UNIQUE_ORACLE_MODELS, query_count):
        raise RuntimeError("accepted query bank has insufficient model diversity")
    provisional = {
        "schema": SCHEMA,
        "graph_name": graph.name,
        "graph_sha256": graph.sha256,
        "graph_git_blob_sha1": blob,
        "n": graph.n,
        "edges": graph.edges,
        "dsatur_coloring": coloring,
        "dsatur_colors": max(coloring, default=-1) + 1,
        "palette": palette,
        "masks": masks,
        "queries": tuple(queries),
        "generator_attempts": len(attempts),
        "generator_rejections": rejected,
        "generator_unique_model_hashes": len(accepted_models),
        "generator_seed": seed,
        "query_width": query_width,
        "query_count": query_count,
        "clauses": len(clauses),
    }
    case = WorkloadCase(**provisional, case_sha256=_sha_json(provisional))
    case.validate()
    generation = {
        "schema": "spectra.wap_support.generator_receipt.v1",
        "case_sha256": case.case_sha256,
        "attempts": attempts,
        "accepted": len(queries),
        "rejected": rejected,
        "unique_oracle_models": len(accepted_models),
    }
    return case, generation
