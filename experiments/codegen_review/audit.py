"""Independent standard-library audit of complete generation/compatibility records.

No benchmark aggregation, m2cgen import, pickle load or generation is performed.
Hashes establish byte identity, not truthful clocks or outside replication.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import random
import statistics
import xml.etree.ElementTree as ET

NAMES=('wine-101','wdbc-101','chess-101','penguins-101','titanic-101','zoo-101','har')
VARIANTS=('stock','guard','single')


def decode(text):
    def unique(pairs):
        result={}
        for k,v in pairs:
            if k in result:raise ValueError('duplicate JSON key')
            result[k]=v
        return result
    def constant(v):raise ValueError('nonfinite JSON token')
    return json.loads(text,object_pairs_hook=unique,parse_constant=constant)


def read(path):return decode(Path(path).read_text())


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def audit(run, models, packages, script, prior_sources):
    protocol=read(run/'protocol.json')
    jobs=[(n,r,v) for n in NAMES for r in range(1 if n=='har' else 3) for v in VARIANTS]
    random.Random(20260928).shuffle(jobs)
    if protocol['jobs']!=[list(j) for j in jobs] or protocol['seed']!=20260928 or protocol['cap_seconds']!=120:
        raise ValueError('fixed schedule or cap differs')
    if protocol['script_sha256']!=sha(script):raise ValueError('benchmark script differs')
    if set(protocol['models'])!=set(NAMES) or set(protocol['packages'])!=set(VARIANTS):
        raise ValueError('identity inventory differs')
    for name in NAMES:
        if sha(models/name/'model.pkl')!=protocol['models'][name]:raise ValueError('model differs')
    for v in VARIANTS:
        root=packages/(v+'-review')
        actual={p.relative_to(root).as_posix():sha(p) for p in sorted((root/'m2cgen').rglob('*.py'))}
        if actual!=protocol['packages'][v]:raise ValueError('package differs')
    rows=[]
    for line in (run/'attempts.jsonl').read_text().splitlines():
        # Reuse the strict JSON reader through its decoder-equivalent here.
        obj=decode(line)
        rows.append(obj)
    if len(rows)!=len(jobs):raise ValueError('missing generation attempt')
    for row,expected in zip(rows,jobs):
        name,repeat,variant=expected
        if (row['model'],row['repeat'],row['variant'])!=expected or type(row['repeat']) is not int:
            raise ValueError('reordered attempt')
        folder=run/f'{name}-{repeat}-{variant}'
        if row['status']=='COMPLETE':
            if row['returncode']!=0:raise ValueError('invalid completion status')
            literal=read(folder/'generation.json')
            if any(row.get(k)!=v for k,v in literal.items()):raise ValueError('observation receipt differs')
            for field in ('generation_ns','generation_cpu_ns','assembly_ns','source_bytes','peak_process_kib'):
                if type(row[field]) is not int or row[field]<=0:raise ValueError('invalid measurement')
            if row['assembly_ns']>row['generation_ns']:raise ValueError('time scope inconsistency')
            path=folder/'model.c'
            if sha(path)!=row['source_sha256'] or path.stat().st_size!=row['source_bytes']:
                raise ValueError('generated bytes differ')
        elif row['status']=='TIMEOUT':
            if row['returncode']!=-9 or row['process_seconds']<120 or (folder/'generation.json').exists():
                raise ValueError('invalid timeout')
        else:raise ValueError('unresolved generation failure')
    tables={}
    for name in NAMES:
        completed=[r for r in rows if r['model']==name and r['status']=='COMPLETE']
        if len({r['source_sha256'] for r in completed})!=1:raise ValueError('generated outputs disagree')
        if name!='har':
            expected=sha(prior_sources/name/'model.c')
            if any(r['source_sha256']!=expected for r in completed):raise ValueError('previous frozen C differs')
        medians={v:statistics.median(r['generation_ns']/1e9 for r in completed if r['variant']==v)
                 if any(r['variant']==v for r in completed) else None for v in VARIANTS}
        tables[name]={'seconds':medians,
                      'single_over_guard':medians['single']/medians['guard'],
                      'single_over_stock':medians['single']/medians['stock'] if medians['stock'] else None}
    return {'status':'PASS','attempts':len(rows),'completed':sum(r['status']=='COMPLETE' for r in rows),
            'timeouts':sum(r['status']=='TIMEOUT' for r in rows),'models':tables,
            'scope':'complete byte identities and derived arithmetic; timings are recorded observations'}


def compare_panel(left,right):
    a,b=read(left/'results.json'),read(right/'results.json')
    if a['models']!=b['models'] or a['languages']!=b['languages'] or a['results']!=b['results']:
        raise ValueError('differential export disagreement')
    for key,value in a['results'].items():
        if value['status']=='OK':
            for folder in (left,right):
                p=folder/(key+'.txt')
                if sha(p)!=value['sha256'] or p.stat().st_size!=value['bytes']:
                    raise ValueError('differential source bytes differ')
    return {'models':len(a['models']),'languages':len(a['languages']),
            'identical_outputs':sum(v['status']=='OK' for v in a['results'].values()),
            'matched_errors':sum(v['status']=='ERROR' for v in a['results'].values())}


def check_upstream(folder, source_roots):
    records=read(folder/'results.json');result={};cases=None
    for r in records:
        name=r['variant'];root=source_roots[name]
        if r['returncode']!=0:raise ValueError('failed upstream tests')
        for file,digest in r['source_sha256'].items():
            p=root/file
            if not p.resolve().is_relative_to(root.resolve()) or sha(p)!=digest:
                raise ValueError('upstream code identity differs')
        tree=ET.parse(folder/(name+'.xml')).getroot();tests=tree.findall('.//testcase')
        current=sorted((t.attrib['classname'],t.attrib['name']) for t in tests)
        if not current or any(tree.findall('.//'+kind) for kind in ('failure','error','skipped')):
            raise ValueError('upstream tests incomplete')
        if cases is not None and current!=cases:raise ValueError('upstream test cases differ')
        cases=current;result[name]=len(tests)
    return {'status':'PASS','tests_per_variant':result,'scope':'original non-e2e upstream suite; repeated cases, not new independent examples'}


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for name in ('run','models','packages','script','prior-sources','out'):p.add_argument('--'+name,type=Path,required=True)
    a=p.parse_args();report=audit(a.run,a.models,a.packages,a.script,a.prior_sources)
    with a.out.open('x') as f:json.dump(report,f,indent=2)
    print(json.dumps(report,indent=2))
